"""Glyph bitmaps for the two original BACKSTREET OATH pixel fonts.

Pure data + tiny helpers. Shared by gen_font.py (TTF builder) and the art
generators (which stamp the same letterforms onto UI sprites).

Grid conventions
----------------
Each glyph is (top_row, [row strings]) where '#' is ink and '.' is empty.

oath_pixel (8 px em, ascent 8, descent 2): rows 0..9
    row 0      = spare ascent row (accents)
    rows 1..7  = cap height (7 px); row 7 sits on the baseline
    rows 3..7  = x-height (5 px)
    rows 8..9  = descender (2 px)

oath_big (12 px em, ascent 11, descent 3): rows 0..13
    row 0      = spare ascent row
    rows 1..10 = cap height (10 px); row 10 sits on the baseline
    rows 4..10 = x-height (7 px)
    rows 11..13 = descender (3 px)

All letterforms are original designs made for this project.
"""

