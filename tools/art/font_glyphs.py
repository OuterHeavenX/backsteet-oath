BIG = {}


def _add(table, ch, top, art, adv=None):
    rows = art.split()
    w = len(rows[0])
    for r in rows:
        assert len(r) == w, (ch, rows)
    table[ch] = (top, rows, adv)


def p(ch, top, art, adv=None):
    _add(PIXEL, ch, top, art, adv)


def b(ch, top, art, adv=None):
    _add(BIG, ch, top, art, adv)


