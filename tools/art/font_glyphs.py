def advance(table, ch, spacing):
    top, rows, adv = table[ch]
    if adv is not None:
        return adv
    return len(rows[0]) + spacing


def text_width(s, big=False):
    table = BIG if big else PIXEL
    sp = BIG_SPACING if big else PIXEL_SPACING
    space = BIG_SPACE_ADV if big else PIXEL_SPACE_ADV
    w = 0
    for ch in s:
        if ch == ' ':
            w += space
        elif ch in table:
            w += advance(table, ch, sp)
    return max(0, w - sp)


def text_pixels(s, big=False):
    """Yield (x, y) pixel coords for string s; y=0 is the top of the ascent."""
    table = BIG if big else PIXEL
    sp = BIG_SPACING if big else PIXEL_SPACING
    space = BIG_SPACE_ADV if big else PIXEL_SPACE_ADV
    x = 0
    for ch in s:
        if ch == ' ':
            x += space
            continue
        if ch not in table:
            continue
        top, rows, adv = table[ch]
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c == '#':
                    yield x + rx, top + ry
        x += advance(table, ch, sp)
